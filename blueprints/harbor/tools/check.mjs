import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { buildCompose, yaml } from './render-compose.mjs';

const root = new URL('../', import.meta.url);
const require = createRequire(new URL('../../app/package.json', root));
const toml = require('@iarna/toml');
const YAML = require('yaml');
const read = async file => readFile(new URL(file, root), 'utf8');
const lock = JSON.parse(await read('images.lock.json'));
const source = JSON.parse(await read('tools/build-source.json'));
const composeText = await read('docker-compose.yml');
const compose = YAML.parse(composeText);
assert.deepEqual(compose, buildCompose(lock, source));
assert.equal(composeText, '# Generated by tools/render-compose.mjs from images.lock.json.\n' + yaml(compose));
assert.match(source.revision, /^[a-f0-9]{40}$/);
for (const file of ['Dockerfile', '.dockerignore', 'harbor/common.py', 'harbor/initialize.py',
                    'images.lock.json', 'vendor/harbor.yml.tmpl']) {
  const pinned = execFileSync('git', ['show', source.revision + ':blueprints/harbor/' + file],
    { cwd: fileURLToPath(root), encoding: 'utf8' });
  assert.equal((await read(file)).replace(/\r\n/g, '\n'), pinned.replace(/\r\n/g, '\n'),
    file + ': commit the updated init source and update tools/build-source.json');
}
assert.equal(createHash('sha256').update(await read('vendor/harbor.yml.tmpl')).digest('hex'), lock.template_sha256);
assert.equal(Object.keys(compose.services).length, 11);
assert.ok(!compose.networks);
assert.ok(!compose.services.operations);
for (const [name, service] of Object.entries(compose.services)) {
  for (const key of ['ports', 'networks', 'container_name', 'env_file', 'privileged']) assert.ok(!service[key], name + ': ' + key);
  assert.ok(!JSON.stringify(service).match(/docker\.sock|BACKUP_|RESTIC_|POLICY_PROJECTS/));
  if (name === 'harbor-init') {
    assert.equal(service.restart, 'no');
    assert.equal(service.build.context, source.repository + '#' + source.revision + ':blueprints/harbor');
  } else {
    assert.match(service.image, /:v2\.15\.4@sha256:[a-f0-9]{64}$/);
    assert.equal(service.depends_on['harbor-init'].condition, 'service_completed_successfully');
  }
}
const configText = await read('template.toml');
const config = toml.parse(configText);
assert.equal(config.config.domains[0].serviceName, 'proxy');
assert.equal(config.config.domains[0].port, 8080);
assert.equal(config.config.domains[0].https, true);
assert.ok(config.config.env.includes('HARBOR_HOSTNAME=${main_domain}'));
assert.notEqual(config.variables.admin_password, '${db_password}');
// Match the catalogue's TemplateDialog payload exactly, including Unicode encoding.
const payload = { compose: composeText, config: configText };
const encoded = Buffer.from(JSON.stringify(payload, null, 2)).toString('base64');
assert.deepEqual(JSON.parse(Buffer.from(encoded, 'base64').toString('utf8')), payload);
const artifacts = new URL('../../.harbor-validation/', root);
await mkdir(artifacts, { recursive: true });
await writeFile(new URL('harbor-import.base64.txt', artifacts), encoded + '\n');
console.log('Harbor YAML, TOML, pinned build source, persistence, isolation and catalogue import checks passed.');
console.log('Import artifact: ' + fileURLToPath(new URL('harbor-import.base64.txt', artifacts)));
