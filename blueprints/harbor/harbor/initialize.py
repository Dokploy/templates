"""Prepare Harbor with upstream tooling; only this container writes runtime configs."""
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shlex
import socket
import subprocess
import sys
import tempfile

from common import ConfigError, atomic_json, boolean, integer, operation_lock, read_json, settings, text

APP = Path(__file__).resolve().parent
CONTROL = Path('/control')
DATA = Path('/data')
CONFIG = Path('/config')

# Services consume only their own generated config directory.
SERVICES = {
    'core': ('core', '/etc/core', 'harbor-core', 10000),
    'postgresql': ('db', '/run/harbor-config', 'harbor-db', 999),
    'redis': ('redis', '/run/harbor-config', 'valkey-photon', 999),
    'registry': ('registry', '/etc/registry', 'registry-photon', 10000),
    'registryctl': ('registryctl', '/etc/registryctl', 'harbor-registryctl', 10000),
    'jobservice': ('jobservice', '/etc/jobservice', 'harbor-jobservice', 10000),
    'portal': ('portal', '/run/harbor-config', 'harbor-portal', 10000),
    'proxy': ('nginx', '/etc/nginx', 'nginx-photon', 10000),
    'trivy-adapter': ('trivy-adapter', '/run/harbor-config', 'trivy-adapter-photon', 10000),
    'exporter': ('exporter', '/run/harbor-config', 'harbor-exporter', 10000),
}

def password(env, name):
    value = text(env, name, required=True)
    if len(value) < 20 or value in ('Harbor12345', 'root123'):
        raise ConfigError(f'{name} must contain at least 20 characters')
    return value

def build_config(env, template):
    # JSON serialization below is also valid YAML. Never interpolate secrets into YAML text.
    conf = json.loads(json.dumps(template))
    conf['hostname'] = text(env, 'HARBOR_HOSTNAME', required=True)
    conf['external_url'] = 'https://' + conf['hostname']
    conf.pop('https', None)
    conf['http'] = {'port': 80}
    conf['internal_tls'] = {'enabled': False}
    conf['data_volume'] = '/data'
    conf['harbor_admin_password'] = password(env, 'HARBOR_ADMIN_PASSWORD')
    conf['database']['password'] = password(env, 'HARBOR_DB_PASSWORD')
    conf['database']['max_idle_conns'] = integer(env, 'DB_MAX_IDLE_CONNS', 10, maximum=100)
    conf['database']['max_open_conns'] = integer(env, 'DB_MAX_OPEN_CONNS', 100, maximum=500)
    if conf['database']['max_idle_conns'] > conf['database']['max_open_conns']:
        raise ConfigError('DB_MAX_IDLE_CONNS must not exceed DB_MAX_OPEN_CONNS')
    db_limit = integer(env, 'POSTGRES_MAX_CONNECTIONS', 256, minimum=20, maximum=10000)
    if conf['database']['max_open_conns'] * 2 + 10 > db_limit:
        raise ConfigError('POSTGRES_MAX_CONNECTIONS must cover core/exporter pools (2 * DB_MAX_OPEN_CONNS + 10)')
    conf['x-dokploy-database-connections'] = db_limit
    conf['jobservice']['max_job_workers'] = integer(env, 'JOB_MAX_WORKERS', 5, maximum=100)
    level = text(env, 'HARBOR_LOG_LEVEL', 'info')
    if level not in ('debug', 'info', 'warning', 'error', 'fatal'):
        raise ConfigError('Invalid HARBOR_LOG_LEVEL')
    conf['log']['level'] = level
    conf['log']['local']['location'] = '/data/log'
    conf['metric'] = {'enabled': True, 'port': 9090, 'path': '/metrics'}
    conf['cache'] = {'enabled': boolean(env, 'CACHE_ENABLED', True), 'expire_hours': 24}
    conf['network'] = {'allow_private_network_access': boolean(env, 'ALLOW_PRIVATE_NETWORK_ACCESS', False)}
    conf['content_trust'] = {'legacy_signer_pull_enabled': False}
    conf['x-dokploy-security'] = {'auth_mode': 'db_auth', 'self_registration': False,
                                  'project_creation_restriction': 'adminonly',
                                  'storage_per_project': integer(env, 'PROJECT_QUOTA_GIB', 20, maximum=1048576) * 1024**3}
    conf['trivy'].update({
        'insecure': False, 'ignore_unfixed': False, 'skip_update': False,
        'skip_java_db_update': False, 'offline_scan': False,
        'github_token': text(env, 'TRIVY_GITHUB_TOKEN'),
        'db_repository': text(env, 'TRIVY_DB_REPOSITORY', 'ghcr.io/aquasecurity/trivy-db'),
        'java_db_repository': text(env, 'TRIVY_JAVA_DB_REPOSITORY', 'ghcr.io/aquasecurity/trivy-java-db'),
    })
    conf['proxy'] = {
        'http_proxy': text(env, 'HARBOR_HTTP_PROXY'), 'https_proxy': text(env, 'HARBOR_HTTPS_PROXY'),
        'no_proxy': text(env, 'HARBOR_NO_PROXY'), 'components': ['core', 'jobservice', 'trivy'],
    }
    return conf

def parse_literal_env(value):
    """Upstream emits raw KEY=value, not shell syntax or Compose interpolation."""
    result = {}
    for line in value.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        key, sep, item = line.partition('=')
        if not sep or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', key):
            raise ConfigError('Invalid environment key generated by upstream prepare')
        if '\x00' in item:
            raise ConfigError('NUL in generated environment')
        result[key] = item
    return result

def launcher(environment, command):
    if not command:
        raise ConfigError('Missing upstream startup command')
    lines = ['#!/bin/sh', 'set -eu',
             'if [ ! -f /run/harbor-control/ready ]; then',
             '  echo "Harbor initialization incomplete" >&2; exit 75', 'fi']
    for key, value in environment.items():
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', key):
            raise ConfigError('Invalid environment key')
        lines.append('export ' + key + '=' + shlex.quote(value))
    lines.append('exec ' + ' '.join(shlex.quote(part) for part in command) + ' "$@"')
    return '\n'.join(lines) + '\n'

def owned_file(path, content, uid=10000, mode=0o600):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    os.chown(path, uid, uid)
    path.chmod(mode)

def finalize(lock, conf):
    # Match upstream's individual file mounts using directory subpaths instead.
    for src, dst in (
        (DATA / 'secret/core/private_key.pem', CONFIG / 'core/private_key.pem'),
        (DATA / 'secret/keys/secretkey', CONFIG / 'core/key'),
        (DATA / 'secret/registry/root.crt', CONFIG / 'registry/root.crt'),
    ):
        owned_file(dst, src.read_text())
    for service, (folder, target, image, uid) in SERVICES.items():
        directory = CONFIG / folder
        directory.mkdir(parents=True, exist_ok=True)
        env_path = directory / 'env'
        environment = parse_literal_env(env_path.read_text()) if env_path.exists() else {}
        if service == 'core':
            environment['CONFIG_OVERWRITE_JSON'] = json.dumps(conf['x-dokploy-security'])
        if service == 'postgresql':
            owned_file(directory / 'health.sh', launcher(environment, ['/docker-healthcheck.sh']), uid, 0o500)
        image_conf = lock['images'][image]
        command = image_conf['entrypoint'] + image_conf['command']
        owned_file(directory / 'launch.sh', launcher(environment, command), uid, 0o500)
        # All files in one subdirectory are consumed by the same service UID.
        for item in [directory, *directory.rglob('*')]:
            if item.is_symlink():
                raise ConfigError('Unexpected symlink in generated configuration')
            os.chown(item, uid, uid)
            item.chmod(0o700 if item.is_dir() else (0o500 if item.name in ('launch.sh', 'health.sh') else 0o600))
    shared = CONFIG / 'shared/trust-certificates'
    shared.mkdir(parents=True, exist_ok=True)
    shared.chmod(0o755)
    # Portal expects a single config file at this fixed path.
    # Compose mounts the generated portal directory under /run/harbor-config.
    portal = CONFIG / 'portal/launch.sh'
    original = lock['images']['harbor-portal']
    owned_file(portal, launcher({}, original['entrypoint'] + ['nginx', '-c', '/run/harbor-config/nginx.conf', '-g', 'daemon off;']), 10000, 0o500)


def fingerprint(conf, lock):
    content = json.dumps({'configuration': conf, 'images': lock}, sort_keys=True).encode()
    for file in ('initialize.py', 'common.py'):
        content += (APP / file).read_bytes()
    return hashlib.sha256(content).hexdigest()

def require_stopped_services():
    # An explicit reconfiguration must never rewrite configs of running workloads.
    for host, port in [('core', 8080), ('postgresql', 5432), ('redis', 6379),
                       ('registry', 5000), ('registryctl', 8080), ('jobservice', 8080),
                       ('portal', 8080), ('proxy', 8080), ('trivy-adapter', 8080), ('exporter', 8080)]:
        try:
            connection = socket.create_connection((host, port), timeout=2)
        except OSError:
            continue
        connection.close()
        raise ConfigError('Stop all Harbor services before --reconfigure; reachable service: ' + host)


def check_persistent_state(old, runtime, digest, generated_complete, database_exists, secrets_complete, reconfigure):
    if old and old['instance'] != runtime['instance']:
        raise ConfigError('HARBOR_INSTANCE_ID must remain unchanged for existing volumes')
    if (old or database_exists) and not secrets_complete:
        raise ConfigError('Persistent encryption/signing keys are missing; restore the original data instead of regenerating keys')
    if old and (old['fingerprint'] != digest or not generated_complete) and not reconfigure:
        raise ConfigError('Configuration changed. Stop Harbor, then run harbor-init --reconfigure (see instructions.md)')


def main(reconfigure=False):
    env = dict(os.environ)
    runtime = settings(env)
    if platform.machine() not in ('x86_64', 'AMD64'):
        raise ConfigError('The locked Harbor distribution requires a Linux amd64 host')
    lock = read_json(APP / 'images.lock.json')
    runtime['harbor_version'] = lock['harbor_version']
    CONTROL.mkdir(parents=True, exist_ok=True)
    CONTROL.chmod(0o755)
    with operation_lock(CONTROL):
        if reconfigure:
            require_stopped_services()
        import yaml
        conf = build_config(env, yaml.safe_load((APP / 'harbor.yml.tmpl').read_text()))
        digest = fingerprint(conf, lock)
        state_file = DATA / 'render-state.json'
        old = read_json(state_file) if state_file.exists() else None
        required_secrets = [DATA / 'secret/keys/secretkey', DATA / 'secret/core/private_key.pem', DATA / 'secret/registry/root.crt']
        database_exists = any((DATA / 'database').iterdir())
        generated_complete = all((CONFIG / folder / 'launch.sh').is_file() for folder, _, _, _ in SERVICES.values())
        check_persistent_state(old, runtime, digest, generated_complete, database_exists,
                               all(item.is_file() for item in required_secrets), reconfigure)
        if old and old['fingerprint'] == digest and generated_complete:
            (CONTROL / 'ready').touch(mode=0o644)
            print('Configuration unchanged; persistent secrets preserved')
            return
        (CONTROL / 'ready').unlink(missing_ok=True)
        with tempfile.TemporaryDirectory() as temp:
            config_input = Path(temp) / 'harbor.yml'
            config_input.write_text(json.dumps(conf, indent=2))
            config_input.chmod(0o600)
            Path('/compose_location').mkdir(parents=True, exist_ok=True)
            # Prepare logs include paths only. Capture errors to avoid dumping secret-bearing configs.
            result = subprocess.run(['python3', '/usr/src/app/main.py', 'prepare', '--with-trivy', '--conf', str(config_input)],
                                    cwd='/usr/src/app', stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            if result.returncode:
                error_log = CONTROL / 'prepare-error.log'
                error_log.write_bytes(result.stdout)
                error_log.chmod(0o600)
                raise ConfigError('Upstream prepare failed; configuration remains unready. Private details: control volume prepare-error.log')
            (CONTROL / 'prepare-error.log').unlink(missing_ok=True)
        finalize(lock, conf)
        atomic_json(state_file, {'fingerprint': digest, 'harbor_version': lock['harbor_version'], 'instance': runtime['instance']})
        (CONTROL / 'ready').touch(mode=0o644)
        print('Harbor configuration prepared')

if __name__ == '__main__':
    try:
        if sys.argv[1:] not in ([], ['--reconfigure']):
            raise ConfigError('Usage: initialize.py [--reconfigure]')
        main(reconfigure=sys.argv[1:] == ['--reconfigure'])
    except ConfigError as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
